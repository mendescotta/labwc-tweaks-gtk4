#!/usr/bin/env python3
"""Generate the audited scalar settings inventory from a labwc-tweaks checkout.
Usage: python3 tools/import-settings.py /path/to/labwc-tweaks
Writes src/schema.rs relative to this script. Never executes upstream code.
Complex acceleration and layout editors are maintained separately.
"""
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

def generate(source):
    pages = []
    for page in ("appearance", "behaviour", "mouse", "keyboard", "touchscreen"):
        text = (source / "src" / (page + ".cpp")).read_text()
        fields = []
        tree=ET.parse(source / "src" / (page + ".ui"))
        labels={}
        for layout in tree.iter("layout"):
            rows={}
            for item in layout.findall("item"):
                widget=item.find("widget")
                if widget is not None:
                    rows.setdefault(item.get("row"),[]).append(widget)
            for widgets in rows.values():
                label=next((w.findtext("property[@name='text']/string") for w in widgets if w.get("class")=="QLabel"),None)
                for w in widgets:
                    own=w.findtext("property[@name='text']/string")
                    if own or label:labels[w.get("name")]=own or label

        pattern = r'settingsAdd(Xml|Env)(Str|Int|Boo|Flt)\("([^"]+)",\s*([^;]+)\);'
        for storage, kind, key, default in re.findall(pattern, text):
            key = key.removeprefix("/labwc_config/")
            if key == "XKB_DEFAULT_LAYOUT":
                default = '""'
            if default.startswith('"'):
                default = json.loads(default)
            else:
                default = default.removesuffix("f")
                default = {"true": "yes", "false": "no"}.get(default, default)
            label = re.sub(r"([a-z])([A-Z])", r"\1 \2", key.split("/")[-1]).replace("_", " ").capitalize()
            if page == "behaviour":
                label = key.split("/")[0].capitalize() + ": " + label
            original=("/labwc_config/" if storage=="Xml" else "")+key
            widget=re.search(r'ui->(\w+)->[^;]*get(?:Str|Int|Bool|Float)\("' + re.escape(original) + r'"', text)
            if widget:label=labels.get(widget.group(1),label)
            if key in ("libinput/device/dragLock","libinput/device/threeFingerDrag"):kind="Str"
            fields.append((label, key, default, {"Str":"text", "Int":"integer", "Boo":"bool", "Flt":"number"}[kind]))
        if not fields:
            raise ValueError("No fields extracted for " + page)
        pages.append((page.capitalize(), fields))
    lines = ['// Generated by tools/import-settings.py; review changes against upstream.',
             "pub type Field = (&'static str, &'static str, &'static str, &'static str);",
             "pub fn pages() -> Vec<(&'static str, Vec<Field>)> { let mut result=vec!["]
    for page, fields in pages:
        lines.append('(' + json.dumps(page) + ', vec![')
        for field in fields:
            lines.append('(' + ','.join(json.dumps(v, ensure_ascii=False) for v in field) + '),')
        lines.append(']),')
    lines.append(']; result.extend(crate::extra::pages()); result }')
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    output = generate(pathlib.Path(sys.argv[1]))
    (pathlib.Path(__file__).resolve().parents[1] / "src/schema.rs").write_text(output)

    used=set(re.findall(r'\("([^"]+)",',output))
    used.update(["Appearance","Behaviour","Mouse","Mouse & Touchpad","Keyboard","Touchscreen","About","Apply","Step","Points","Define Motion curve","Define Scroll curve","Define Fallback curve"])
    localized=["// Generated from upstream Qt translations; GPL-2.0-only.", "pub fn translate(source: &str) -> &str {",
        'let locale=std::env::var("LC_ALL").ok().filter(|s|!s.is_empty()).or_else(||std::env::var("LC_MESSAGES").ok()).or_else(||std::env::var("LANG").ok()).unwrap_or_default();',
        'let language=locale.split(".").next().unwrap_or("").split("@").next().unwrap_or("");',
         'let language=match language { "pt_BR"|"zh_CN"|"zh_TW"=>language,_=>language.split("_").next().unwrap_or(language)};', 'match language {']
    for path in sorted((pathlib.Path(sys.argv[1])/"data/translations").glob("labwc-tweaks_*.ts")):
        root=ET.parse(path).getroot()
        lang=root.get("language",path.stem.removeprefix("labwc-tweaks_"))
        translations={}
        for message in root.iter("message"):
            src=message.findtext("source")
            translated=message.find("translation")
            if src in used and translated is not None and translated.get("type") not in ("unfinished","obsolete","vanished") and translated.text:
                translations.setdefault(src,translated.text)
        if not translations:continue
        localized.append(json.dumps(lang)+' => match source {')
        for src,value in translations.items():
            localized.append(json.dumps(src,ensure_ascii=False)+' => '+json.dumps(value,ensure_ascii=False)+',')
        localized.append('_ => source },')
    localized.extend(['_ => source,','}','}'])
    (pathlib.Path(__file__).resolve().parents[1]/"src/localization.rs").write_text("\n".join(localized)+"\n")
